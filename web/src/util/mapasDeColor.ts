export type MapaDeColor = 'inferno' | 'cividis'
export type MapaDivergente = 'berlin'

const TABLAS: Record<MapaDeColor | MapaDivergente, string> = {
  inferno: INFERNO,
  cividis: CIVIDIS,
  berlin: BERLIN,
}

/** RGBA de 256 × 1, listo para subir como textura o pintar en un canvas 2D. */
export function tablaRgba(mapa: MapaDeColor | MapaDivergente): Uint8Array {
  const hex = TABLAS[mapa]
  const rgba = new Uint8Array(256 * 4)
  for (let i = 0; i < 256; i++) {
    rgba[i * 4] = parseInt(hex.slice(i * 6, i * 6 + 2), 16)
    rgba[i * 4 + 1] = parseInt(hex.slice(i * 6 + 2, i * 6 + 4), 16)
    rgba[i * 4 + 2] = parseInt(hex.slice(i * 6 + 4, i * 6 + 6), 16)
    rgba[i * 4 + 3] = 255
  }
  return rgba
}

/** Color CSS en la posición t (0 a 1) del mapa, para la barra de la leyenda. */
export function colorCss(mapa: MapaDeColor | MapaDivergente, t: number): string {
  const i = Math.round(Math.min(1, Math.max(0, t)) * 255)
  return `#${TABLAS[mapa].slice(i * 6, i * 6 + 6)}`
}
